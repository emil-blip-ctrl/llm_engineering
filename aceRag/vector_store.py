
"""
Chroma vector-store service for the ACE RAG project.

Responsibilities:
- Persist the Chroma database on a Modal Volume.
- Store document chunks with their precomputed embeddings and metadata.
- Retrieve the nearest chunks for one or more query embeddings.
- Return candidates to the local RAG pipeline for deduplication and reranking.

Embedding generation is handled separately by modal_compute.py.
Query expansion, reranking, and answer generation stay local.
"""

from __future__ import annotations

import json
from typing import Any
from app import app

import modal


# Keep these values aligned with config.py.
VOLUME_NAME = "ace-rag-chroma"
CHROMA_PERSIST_DIR = "/data/chroma"
CHROMA_COLLECTION_NAME = "ace_documentation"

# This service needs Chroma, but not a GPU or the embedding model.
image = (
    modal.Image.debian_slim(python_version="3.11")
    .pip_install(
        "chromadb",
        "huggingface_hub",
    )
    .add_local_python_source("app")
)


volume = modal.Volume.from_name(
    VOLUME_NAME,
    create_if_missing=True,
)


def _serialize_metadata(metadata: dict[str, Any]) -> dict[str, Any]:
    """
    Convert metadata into types supported by Chroma.

    Scalar strings, integers, floats, and booleans remain unchanged.
    Lists, dictionaries, and other unsupported values become JSON strings.
    None values are omitted.
    """
    result: dict[str, Any] = {}

    for key, value in metadata.items():
        if value is None:
            continue

        if isinstance(value, (str, int, float, bool)):
            result[key] = value
        else:
            result[key] = json.dumps(
                value,
                ensure_ascii=False,
                default=str,
            )

    return result


def _get_collection(client: Any) -> Any:
    """Get or create the ACE documentation collection."""
    return client.get_or_create_collection(
        name=CHROMA_COLLECTION_NAME,
        metadata={"hnsw:space": "cosine"},
    )


@app.function(
    image=image,
    volumes={CHROMA_PERSIST_DIR: volume},
    timeout=900,
)
def upsert_chunks(
    chunks: list[dict[str, Any]],
    embeddings: list[list[float]],
) -> dict[str, Any]:
    """
    Add or update document chunks and their precomputed embeddings.

    Each chunk must contain:
        id: Unique, stable chunk identifier.
        text: Original chunk text.
        metadata: Dictionary containing source information and enrichment.

    `embeddings[i]` must correspond to `chunks[i]`.

    Reusing the same chunk ID updates that record instead of creating
    a duplicate. The original text is stored without metadata being
    appended to it.
    """
    if len(chunks) != len(embeddings):
        raise ValueError(
            "The number of chunks must match the number of embeddings."
        )

    if not chunks:
        return {"upserted": 0, "collection": CHROMA_COLLECTION_NAME}

    ids: list[str] = []
    documents: list[str] = []
    metadatas: list[dict[str, Any]] = []

    for index, chunk in enumerate(chunks):
        chunk_id = str(chunk.get("id", "")).strip()
        text = chunk.get("text")

        if not chunk_id:
            raise ValueError(f"Chunk at index {index} has no ID.")

        if not isinstance(text, str) or not text.strip():
            raise ValueError(
                f"Chunk {chunk_id!r} has empty or invalid text."
            )

        if not embeddings[index]:
            raise ValueError(
                f"Chunk {chunk_id!r} has an empty embedding."
            )

        ids.append(chunk_id)
        documents.append(text)
        metadatas.append(
            _serialize_metadata(chunk.get("metadata", {}))
        )

    # Reload committed changes before opening Chroma.
    volume.reload()

    import chromadb

    client = chromadb.PersistentClient(path=CHROMA_PERSIST_DIR)

    try:
        collection = _get_collection(client)

        collection.upsert(
            ids=ids,
            documents=documents,
            metadatas=metadatas,
            embeddings=embeddings,
        )

        count = collection.count()
    finally:
        client.close()

    # Persist database changes to the Modal Volume.
    volume.commit()

    return {
        "upserted": len(ids),
        "collection_count": count,
        "collection": CHROMA_COLLECTION_NAME,
    }


@app.function(
    image=image,
    volumes={CHROMA_PERSIST_DIR: volume},
    timeout=300,
)
def query_vectors(
    query_embeddings: list[list[float]],
    n_results: int = 10,
    where: dict[str, Any] | None = None,
) -> list[list[dict[str, Any]]]:
    """
    Retrieve nearest document chunks for multiple query embeddings.

    Inputs:
        query_embeddings: Precomputed vectors generated by
            modal_compute.py using input_type="query".
        n_results: Maximum number of candidates per query.
        where: Optional Chroma metadata filter.

    Returns one candidate list per query embedding. Each candidate
    contains its ID, original text, metadata, and cosine distance.

    Lower cosine distance indicates greater similarity.
    """
    if n_results < 1:
        raise ValueError("n_results must be at least 1.")

    if not query_embeddings:
        return []

    if any(not vector for vector in query_embeddings):
        raise ValueError("Query embeddings must not be empty.")

    # Reload committed index changes before reading the database.
    volume.reload()

    import chromadb

    client = chromadb.PersistentClient(path=CHROMA_PERSIST_DIR)

    try:
        collection = _get_collection(client)

        collection_size = collection.count()

        if collection_size == 0:
            return [[] for _ in query_embeddings]

        result_count = min(n_results, collection_size)

        results = collection.query(
            query_embeddings=query_embeddings,
            n_results=result_count,
            where=where,
            include=[
                "documents",
                "metadatas",
                "distances",
            ],
        )

        candidates_by_query: list[list[dict[str, Any]]] = []

        for query_index, ids in enumerate(results["ids"]):
            candidates: list[dict[str, Any]] = []

            for result_index, chunk_id in enumerate(ids):
                candidates.append(
                    {
                        "id": chunk_id,
                        "text": results["documents"][query_index][
                            result_index
                        ],
                        "metadata": results["metadatas"][query_index][
                            result_index
                        ],
                        "distance": results["distances"][query_index][
                            result_index
                        ],
                    }
                )

            candidates_by_query.append(candidates)

        return candidates_by_query

    finally:
        client.close()


@app.function(
    image=image,
    volumes={CHROMA_PERSIST_DIR: volume},
    timeout=120,
)
def collection_info() -> dict[str, Any]:
    """Return basic information about the stored collection."""
    volume.reload()

    import chromadb

    client = chromadb.PersistentClient(path=CHROMA_PERSIST_DIR)

    try:
        collection = _get_collection(client)

        return {
            "collection": CHROMA_COLLECTION_NAME,
            "count": collection.count(),
            "persist_directory": CHROMA_PERSIST_DIR,
        }
    finally:
        client.close()


@app.function(
    image=image,
    volumes={CHROMA_PERSIST_DIR: volume},
    secrets=[modal.Secret.from_name("huggingface-secret")],
    timeout=1800,
)
def upload_chroma_to_huggingface() -> dict:
    import os
    from huggingface_hub import HfApi

    # Refresh the mounted Volume.
    volume.reload()

    repo_id = "emitev/ace-rag-data"

    if not os.path.exists(
        os.path.join(CHROMA_PERSIST_DIR, "chroma.sqlite3")
    ):
        raise FileNotFoundError(
            "Chroma database file was not found."
        )

    api = HfApi()

    # Create the dataset repository if it does not exist.
    api.create_repo(
        repo_id=repo_id,
        repo_type="dataset",
        exist_ok=True,
    )

    # Upload the complete Chroma persistence directory.
    commit_info = api.upload_folder(
        folder_path=CHROMA_PERSIST_DIR,
        path_in_repo="chroma",
        repo_id=repo_id,
        repo_type="dataset",
        commit_message="Upload Chroma database snapshot",
    )

    return {
        "status": "success",
        "repository": repo_id,
        "path": "chroma/",
        "commit": commit_info.oid,
    }
